	FROM POSTS P
	INNER JOIN COLLECTIONS C ON C.ID = P.COLLECTION_ID
	LEFT JOIN INTERACTIONS I ON P.ID = I.POST_ID AND I.SCOPE='VIEW'
	LEFT JOIN POST_STAT PS ON PS.POST_ID = P.ID
