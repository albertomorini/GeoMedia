CREATE PROCEDURE [dbo].[COLLECTIONS_MERGE]
	@JSON NVARCHAR(MAX)
AS
BEGIN

	MERGE INTO COLLECTIONS AS target
    USING (
        SELECT *
	FROM OPENJSON(@json)
        WITH (
            ID INT,
            TITLE VARCHAR(50),
            OWNERID INT,
            DESCRIPTION VARCHAR(256),
            CREATORS NVARCHAR(MAX),
            VIEWERS NVARCHAR(MAX),
            EXCL_DATE_START DATETIME,
            EXCL_DATE_END DATETIME,
            RECURRENT NVARCHAR(20),
            REMOTE_POSTING BIT,
            SEQUENTIALS NVARCHAR(MAX)
        )
    ) AS source
    ON target.ID = source.ID

    WHEN MATCHED THEN
        UPDATE SET
            TITLE = source.TITLE,
            OWNERID = source.OWNERID,
            DESCRIPTION = source.DESCRIPTION,
            DM = GETDATE(),
            CREATORS = source.CREATORS,
            VIEWERS = source.VIEWERS,
            EXCL_DATE_START = source.EXCL_DATE_START,
            EXCL_DATE_END = source.EXCL_DATE_END,
            RECURRENT = source.RECURRENT,
            REMOTE_POSTING = source.REMOTE_POSTING,
            SEQUENTIALS = source.SEQUENTIALS

    WHEN NOT MATCHED THEN
        INSERT (
            TITLE, OWNERID, DESCRIPTION, DC,DM,
            CREATORS, VIEWERS, EXCL_DATE_START, EXCL_DATE_END,
            RECURRENT,  REMOTE_POSTING,
            SEQUENTIALS
        )
        VALUES (
            source.TITLE, source.OWNERID, source.DESCRIPTION, GETDATE(),GETDATE(),
            source.CREATORS, source.VIEWERS, source.EXCL_DATE_START, source.EXCL_DATE_END,
            source.RECURRENT,source.REMOTE_POSTING,
            source.SEQUENTIALS
        );

END
