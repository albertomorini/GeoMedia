CREATE  PROCEDURE [dbo].[AUTH_CHECK_OTP]
@JSON NVARCHAR(MAX)
AS
BEGIN
    DECLARE @MSG NVARCHAR(1000) 

    IF EXISTS(
        SELECT * FROM USERS WHERE USERNAME=JSON_VALUE(@JSON,'$.USERNAME') AND OTPCODE = CAST(JSON_VALUE(@JSON,'$.OTP') AS INT)
        AND DATEDIFF(hour,OTPDATE,GETDATE())<=1 --OTP generated within an hour
    )
    BEGIN
        UPDATE USERS SET EMAIL_VERIFIED = 1, DM=GETDATE(), OTPDATE=GETDATE() WHERE USERNAME= JSON_VALUE(@JSON,'$.USERNAME')
        SELECT 1 AS AUTH, ID AS UID, * FROM USERS WHERE USERNAME= JSON_VALUE(@JSON,'$.USERNAME')
    END
    ELSE
    BEGIN
        SET @MSG = CONCAT('Wrong OPT for users:',JSON_VALUE(@JSON,'$.USERNAME'),' CODE PROVIDED: ' , JSON_VALUE(@JSON,'$.OTP'))
        EXEC LOG_WRITE @MESSAGE=@MSG, @SCOPE='OTP'
        SELECT 0 AS AUTH
    END
END




