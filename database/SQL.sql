CREATE PROCEDURE [dbo].[AUTH_PSW_RESET]
@JSON NVARCHAR(MAX)
AS
BEGIN
	
	DECLARE @MSG VARCHAR(1000)

	UPDATE U
	SET PASSWORD=J.NEWPASSWORD,
	DM=GETDATE(),
	LASTHEADERS= HEADERS,
	LASTIP = IP
	FROM USERS U
	INNER JOIN OPENJSON(@JSON,'$')WITH(
			USERNAMEMAIL VARCHAR(128),
			NEWPASSWORD NVARCHAR(512),
			OTP VARCHAR(6),
			IP VARCHAR(200),
			HEADERS NVARCHAR(MAX) AS JSON
	) J ON (J.USERNAMEMAIL = U.EMAIL OR J.USERNAMEMAIL = U.USERNAME)  AND J.OTP = U.OTPCODE
	
	IF @@ROWCOUNT>0
	BEGIN
		SELECT 1 AS OK
		SET @MSG = CONCAT('PASSWORD RESET COMPLETED USER: ', JSON_VALUE(@JSON,'$.USERNAME'), ' OTP: ', JSON_VALUE(@JSON,'$.OTP'))
		EXEC LOG_WRITE @MESSAGE=@MSG, @SCOPE='PSWRESET'
	END
	ELSE
	BEGIN
		SELECT 0 AS OK
		SET @MSG = CONCAT('wrong otp on psw reset, USER: ', JSON_VALUE(@JSON,'$.USERNAMEMAIL'), ' OTP: ', JSON_VALUE(@JSON,'$.OTP'))
		EXEC LOG_WRITE @MESSAGE=@MSG, @SCOPE='PSWRESET'
	END
END
