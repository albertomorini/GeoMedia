CREATE PROCEDURE [dbo].[AUTH_PSW_FORGOTTEN]
@JSON VARCHAR(MAX)
AS
BEGIN
	DECLARE @OTP VARCHAR(6) = (SELECT RIGHT('000000' + CAST(CAST(RAND() * 1000000 AS INT) AS VARCHAR(6)), 6))

	UPDATE U SET OTPCODE =@OTP, OTPDATE=GETDATE()
	FROM USERS U
	INNER JOIN OPENJSON(@JSON,'$')WITH(
		USERNAMEMAIL VARCHAR(128)
	) J ON J.USERNAMEMAIL = U.EMAIL OR J.USERNAMEMAIL = U.USERNAME

	SELECT @OTP AS OTP, 2 as AUTH, U.EMAIL, U.USERNAME  --IN ORDER TO SEND THE OTP CODE VIA EMAIL
	FROM  USERS U
	INNER JOIN OPENJSON(@JSON,'$')WITH(
		USERNAMEMAIL VARCHAR(128)
	) J ON J.USERNAMEMAIL = U.EMAIL OR J.USERNAMEMAIL = U.USERNAME

END


