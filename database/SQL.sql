CREATE PROCEDURE [dbo].[COLLECTIONS_GET]
	@UID INT,
	@MODE CHAR(1)
-- R (reading/viewing post), W (writing) to check if creator
AS
BEGIN

	IF(@MODE='W')
	BEGIN
		SELECT *
		FROM COLLECTIONS
		WHERE 
		( --EXCLUSIVITY
			GETDATE()> ISNULL(EXCL_DATE_START,DATEADD(DAY,-1,GETDATE())) AND GETDATE() < ISNULL(EXCL_DATE_END,DATEADD(DAY,1,GETDATE())) --IF NULL, MAKE IT FROM YESTERDAY TILL TOMORROW
			AND
			(@UID IN (SELECT VALUE
			FROM OPENJSON(CREATORS,'$')) OR CREATORS IS NOT NULL)
		)OR OWNERID=@UID
	END
	ELSE IF(@MODE='R')
	BEGIN
		SELECT *
		FROM COLLECTIONS
		WHERE 
		( --EXCLUSIVITY
			GETDATE()> ISNULL(EXCL_DATE_START,DATEADD(DAY,-1,GETDATE())) AND GETDATE() < ISNULL(EXCL_DATE_END,DATEADD(DAY,1,GETDATE())) --IF NULL, MAKE IT FROM YESTERDAY TILL TOMORROW
			AND
			(
				(@UID IN (SELECT VALUE
			FROM OPENJSON(VIEWERS,'$')) OR VIEWERS IS NOT NULL) --VIEWER
			OR
			(@UID IN (SELECT VALUE
			FROM OPENJSON(CREATORS,'$')) OR CREATORS IS NOT NULL) -- CREATOR CAN BE VIEWER NO NEED TO SPECIFY
			)
		)OR OWNERID=@UID
	END

END
