        SET @MSG =  CONCAT('DELETED POST', CAST(@POSTID AS VARCHAR(200)))
    END
    ELSE
    BEGIN
        SELECT 0 as OK
        SET @MSG =  CONCAT('CANNOT DELETE POST, WRONG PSW OR POSTID: ', CAST(@POSTID AS VARCHAR(200)), @PASSWORD)
    END

    EXEC dbo.LOG_WRITE @MESSAGE = @MSG, @SCOPE='POST_DELETE'


END




