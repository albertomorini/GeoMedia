    )
    BEGIN
        DELETE FROM INTERACTIONS WHERE POST_ID = @POSTID;
        DELETE FROM HYPERMEDIA WHERE POST_ID = @POSTID;
        DELETE FROM POSTS WHERE ID = @POSTID;
        DELETE FROM REPORTS WHERE POSTID=@POSTID
