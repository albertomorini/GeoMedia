    @PASSWORD VARCHAR(128)
AS
BEGIN
    DECLARE @MSG NVARCHAR(1000)

    IF EXISTS ( 
        SELECT * FROM USERS WHERE 
        ID = (SELECT AUTHOR_ID FROM POSTS WHERE ID = @POSTID) 
