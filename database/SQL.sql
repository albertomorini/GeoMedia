CREATE PROCEDURE [dbo].[AUTH_LOGIN]
	@JSON NVARCHAR(MAX)
AS
BEGIN

	DECLARE @USERNAME VARCHAR(50) = NULL,@EMAIL VARCHAR(128) = NULL, @PASSWORD NVARCHAR(256), @IP VARCHAR(200), @HEADERS NVARCHAR(MAX)

	SELECT @USERNAME=EMAIL, @EMAIL=EMAIL, @PASSWORD=PASSWORD, @IP=IP, @HEADERS=HEADERS
	FROM OPENJSON(@JSON,'$')WITH(
        EMAIL VARCHAR(128),
        PASSWORD NVARCHAR(256),
         IP VARCHAR(200),
        HEADERS NVARCHAR(MAX)
    )

	IF EXISTS (
        SELECT *
	FROM DBO.USERS
	WHERE (USERNAME=@USERNAME OR EMAIL=@EMAIL) AND [PASSWORD] = @PASSWORD
    )
    BEGIN
		SELECT 1 AS AUTH, ID AS UID, USERNAME, EMAIL, NAME, SURNAME
		FROM USERS
		WHERE (USERNAME=@USERNAME OR EMAIL=@EMAIL)

		UPDATE USERS SET LASTIP=@IP, LASTHEADERS=@HEADERS WHERE (USERNAME=@USERNAME OR EMAIL=@EMAIL)
	END
    ELSE
    BEGIN
		SELECT 0 AS AUTH, 'Invalid cretential' as MSG

	END



END


