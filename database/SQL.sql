CREATE procedure [dbo].[HPMEDIA_MERGEFILE]
	@FILESNAME_ATTACHED NVARCHAR(MAX),
	@POSTID INT
AS
BEGIN
	BEGIN TRY

        MERGE HYPERMEDIA AS target
            USING (
                SELECT *
	FROM OPENJSON(@FILESNAME_ATTACHED)
                WITH (
                    filepath NVARCHAR(500),
                    filename NVARCHAR(255),
                    mimetype VARCHAR(32),
                    post_id INT
                )
	WHERE filename IS NOT NULL
            ) AS source
            ON  target.FILENAME = source.filename
		AND target.POST_ID = source.post_id

            WHEN NOT MATCHED BY TARGET THEN
                INSERT (FILEPATH, FILENAME,  POST_ID, MIME_TYPE)
                VALUES (source.filepath, source.filename,  source.post_id,source.mimetype)

            WHEN NOT MATCHED BY SOURCE
            AND target.POST_ID IN (
                SELECT POST_ID
	FROM OPENJSON(@FILESNAME_ATTACHED) WITH (POST_ID INT)
            )
            THEN DELETE;

        SELECT 1 AS OK
    END TRY
    BEGIN CATCH
        SELECT 0 AS OK, ERROR_MESSAGE() AS MSG
    END CATCH

END
