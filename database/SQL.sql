CREATE PROCEDURE [dbo].[AUTH_SIGNIN]
	@JSON NVARCHAR(MAX)
AS
BEGIN

	DECLARE @USERNAME VARCHAR(50), @EMAIL VARCHAR(128),@PASSWORD NVARCHAR(256),@NAME VARCHAR(30)=NULL, @SURNAME VARCHAR(30)=NULL, @IP VARCHAR(200), @HEADERS NVARCHAR(MAX)

	SELECT @USERNAME=USERNAME, @EMAIL=EMAIL, @PASSWORD=PASSWORD, @NAME=NAME, @SURNAME=SURNAME
	FROM OPENJSON(@JSON,'$')WITH(
        USERNAME VARCHAR(50),
        EMAIL VARCHAR(128),
        PASSWORD NVARCHAR(256),
        NAME VARCHAR(30),
        SURNAME VARCHAR(30),
        IP VARCHAR(200),
        HEADERS NVARCHAR(MAX)
    )

	IF NOT EXISTS(
        SELECT *
	FROM USERS
	WHERE [EMAIL]=@EMAIL OR USERNAME = @USERNAME  --TODO: AND AUTH OK (in order to resend the otp)
    )
    BEGIN

		DECLARE @OTP VARCHAR(6) = (SELECT CONVERT(varchar(255),(SELECT CAST(RAND()*1000000 AS INT))))
		INSERT INTO USERS
			(EMAIL, USERNAME, NAME, SURNAME, DC, DM,[PASSWORD],OTPCODE, OTPDATE, LASTIP,LASTHEADERS)
		VALUES(@EMAIL, @USERNAME, @NAME, @SURNAME, GETDATE(), GETDATE(), @PASSWORD, @OTP, GETDATE(), @IP, @HEADERS);

		SELECT @OTP AS OTP, 2 AS AUTH, 'pending otp' as MSG
	END
    ELSE
    BEGIN
		SELECT 0 AS AUTH, 'Username or email already taken' as MSG
