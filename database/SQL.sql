CREATE PROCEDURE [dbo].[PROFILE_EditInfo]
	@JSON NVARCHAR(MAX)
AS
BEGIN
	UPDATE U
	SET
	 U.USERNAME  = ISNULL(JJ.USERNAME , U.USERNAME)
	,U.PASSWORD  = ISNULL(JJ.PASSWORD ,U.PASSWORD)
	,U.EMAIL  = ISNULL(JJ.EMAIL ,U.EMAIL)
	,U.NAME  = ISNULL(JJ.NAME ,U.NAME)
	,U.SURNAME  = ISNULL(JJ.SURNAME ,U.SURNAME)
	,U.PROFILE_PICTURE  = ISNULL(JJ.PROFILE_PICTURE ,U.PROFILE_PICTURE)
	,U.DM = GETDATE()
	FROM USERS U
		INNER JOIN OPENJSON(@JSON,'$.INFO') WITH(
		UID INT
		,USERNAME VARCHAR(50)
		,PASSWORD NVARCHAR(512)
		,EMAIL VARCHAR(128)
		,NAME VARCHAR(30)
		,SURNAME VARCHAR(30)
		,PROFILE_PICTURE NVARCHAR(MAX)
	) JJ ON JJ.UID = U.ID

	SELECT
		ID AS UID,
		USERNAME
	, PASSWORD
	, EMAIL
	, NAME
	, SURNAME
	FROM USERS
	WHERE ID = (
		SELECT JSON_VALUE(@JSON,'$.INFO.UID')
	)

END
